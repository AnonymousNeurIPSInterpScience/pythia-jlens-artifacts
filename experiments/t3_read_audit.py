#!/usr/bin/env python3
"""t3_read_audit.py — the READ audit (Claim 1a), built to PLAN.md §3's instrument fixes.

Three DVs per (model, layer), each with the controls that make it interpretable:

  R1  SELF-READ (diagnostic only, never a readability claim).
      Build v_c = J_l^T W_U[c] for each concept c, transport+unembed it, ask whether c
      returns top-1/top-3. Self-referential by construction (PLAN.md §3.2) -- kept because
      its controls say whether the lens is wired up at all.
      Controls: rand_rot (rotate J), row_shuffle (derange the concept->vector map).

  R2  EXTERNAL AGREEMENT (load-bearing). Compare the lens readout at layer l against the
      model's OWN final-layer next-token distribution: top-1 agreement and KL(lens||final).
      Nothing in R2 is generated by the lens.

  R3  KURTOSIS EXCESS (never raw -- PLAN.md §3.3). Excess kurtosis of the readout logits,
      minus the MAX over three matched nulls: random-rotation J, row-shuffled W_U,
      untransported (= logit lens). Raw kurtosis has null SE ~ sqrt(24/|V|) ~ 0.022 and so
      always "fires"; only the excess over a matched null is informative.

Concept set is >= 250 (PLAN.md §3.1: n=16 gives binomial SE 0.10 and cannot resolve a
scaling curve). Frequency-stratified over the tokenizer's single-token vocabulary.

NO CENTERING anywhere.
"""
from __future__ import annotations

import argparse, json, os, sys, time

import torch

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "jacobian-lens"))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from jlens.hf import Layout, from_hf  # noqa: E402
from jlens.lens import JacobianLens  # noqa: E402
from jlens.hooks import ActivationRecorder  # noqa: E402

PYTHIA_LAYOUT_T5 = Layout("gpt_neox", layers="layers", norm="final_layer_norm",
                          embed="embed_in", lm_head="lm_head")

EVAL_PROMPTS = [
    "The history of the printing press begins in the fifteenth century, when a goldsmith in "
    "Mainz devised a system of movable metal type that could be rearranged and reused again.",
    "In cellular respiration, glucose is oxidised through a sequence of enzyme-catalysed "
    "reactions that release energy gradually and store it in the bonds of adenosine triphosphate.",
    "Ocean currents redistribute heat around the planet, carrying warm surface water northward "
    "while colder and saltier water sinks in the polar regions and returns along the deep basins.",
    "The invention of the telescope transformed astronomy, allowing observers to resolve the "
    "moons of Jupiter and the phases of Venus, which supported the heliocentric model of orbits.",
    "Economic historians argue that the enclosure movement reshaped rural labour markets in "
    "England, pushing displaced agricultural workers toward the growing manufacturing towns.",
]


def build_concept_set(tok, n_concepts: int, seed: int = 0) -> list[tuple[str, int]]:
    """Frequency-stratified single-token concepts.

    BPE merge order makes low token ids roughly more frequent, so we stratify over id
    deciles. Keeps alphabetic, leading-space, length>=3 tokens whose id round-trips.
    """
    vocab_size = len(tok)
    cands: list[tuple[str, int]] = []
    for tid in range(vocab_size):
        s = tok.convert_ids_to_tokens(tid)
        if s is None:
            continue
        s = s.replace("Ġ", " ")
        if not s.startswith(" "):
            continue
        w = s[1:]
        if len(w) < 3 or not w.isalpha() or not w.islower():
            continue
        cands.append((s, tid))
    if not cands:
        raise SystemExit("no candidate concepts found")
    # BUGFIX 2026-08-10 (adversarial review): the previous version took `n // 10` per stratum
    # and then truncated `out[:n]` from the FRONT. Whenever n % 10 != 0 it returned fewer than
    # requested, and the truncation discarded the highest-id (rarest-token) strata entirely —
    # destroying the frequency stratification the docstring promises. Now every stratum is
    # sampled without replacement, remainders are distributed across the earliest strata, and
    # the result is shuffled so no truncation downstream can re-bias it.
    g = torch.Generator().manual_seed(seed)
    n_str = 10
    chunk = max(1, len(cands) // n_str)
    strata = []
    for i in range(n_str):
        lo = i * chunk
        hi = len(cands) if i == n_str - 1 else (i + 1) * chunk
        if lo < len(cands):
            strata.append(cands[lo:hi])
    base, rem = divmod(n_concepts, len(strata))
    out: list[tuple[str, int]] = []
    for i, pool in enumerate(strata):
        want = base + (1 if i < rem else 0)
        take = min(want, len(pool))
        idx = torch.randperm(len(pool), generator=g)[:take].tolist()
        out.extend(pool[j] for j in idx)
    if len(out) < n_concepts:                      # top up from the leftovers, still unbiased
        chosen = {t for _, t in out}
        spare = [c for c in cands if c[1] not in chosen]
        idx = torch.randperm(len(spare), generator=g)[:n_concepts - len(out)].tolist()
        out.extend(spare[j] for j in idx)
    perm = torch.randperm(len(out), generator=g).tolist()
    out = [out[j] for j in perm]
    if len(out) != n_concepts:
        raise SystemExit(f"concept set is {len(out)}, expected {n_concepts}")
    return out


def excess_kurtosis(x: torch.Tensor) -> float:
    """Excess kurtosis of a 1-D tensor (Fisher; 0 for a Gaussian)."""
    x = x.float()
    m = x.mean()
    d = x - m
    var = (d ** 2).mean()
    if float(var) <= 0:
        return float("nan")
    return float((d ** 4).mean() / var ** 2 - 3.0)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="EleutherAI/pythia-70m-deduped")
    ap.add_argument("--lens", required=True)
    ap.add_argument("--n-concepts", type=int, default=250)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    t0 = time.perf_counter()
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    from transformers import AutoModelForCausalLM, AutoTokenizer
    import transformers

    tok = AutoTokenizer.from_pretrained(a.model)
    hf = AutoModelForCausalLM.from_pretrained(a.model, dtype=torch.float32)
    try:
        model = from_hf(hf, tok)
    except ValueError:
        model = from_hf(hf, tok, layout=PYTHIA_LAYOUT_T5)
    lens = JacobianLens.load(a.lens)

    WU = model._lm_head.weight.detach().float()               # [V, d]  UNTIED on Pythia
    concepts = build_concept_set(tok, a.n_concepts, a.seed)
    cids = torch.tensor([c[1] for c in concepts])
    n_c = len(concepts)

    g = torch.Generator().manual_seed(a.seed)
    # derangement for row_shuffle
    if n_c < 2:
        raise SystemExit(f"need >= 2 concepts for a derangement control, got {n_c}")
    perm = torch.randperm(n_c, generator=g)
    for _ in range(10000):                       # bounded; a derangement exists for n_c >= 2
        if not bool((perm == torch.arange(n_c)).any()):
            break
        perm = torch.randperm(n_c, generator=g)
    else:
        raise SystemExit("failed to draw a derangement")

    rows = []
    for l in lens.source_layers:
        J = lens.jacobians[l].float()
        d = J.shape[0]
        Q, _ = torch.linalg.qr(torch.randn(d, d, generator=torch.Generator().manual_seed(100 + l)))

        def read(vecs: torch.Tensor) -> torch.Tensor:
            """unembed(vecs) -> [n, V] logits."""
            with torch.no_grad():
                return model.unembed(vecs).float()

        # ---- R1 self-read + controls ------------------------------------
        # The dictionary vector is v_c = J^T W_U[c] (a direction in LAYER-l space), so the
        # self-read must TRANSPORT it before unembedding: readout = unembed(J @ v_c).
        # Rows of (WU[cids] @ J) are v_c^T; right-multiplying by J.T gives (J v_c)^T.
        # BUGFIX 2026-08-10 (CRITICAL, caught by adversarial review): top_hits previously
        # hard-coded `J.T` as the transport, so the rand_rot control BUILT its dictionary from
        # (Q @ J) but TRANSPORTED with the unrotated J. The arm therefore measured neither the
        # real lens nor the rotated one. The transport matrix is now passed explicitly and must
        # be the same matrix the dictionary was built from.
        def top_hits(M, target_ids):
            """Self-read through transport M: v_c = M^T W_U[c], readout = unembed(M v_c)."""
            lg = read((WU[target_ids] @ M) @ M.T)
            top3 = lg.topk(3, dim=-1).indices
            t1 = float((top3[:, 0] == target_ids).float().mean())
            t3 = float((top3 == target_ids.unsqueeze(1)).any(1).float().mean())
            return t1, t3
        r1_t1, r1_t3 = top_hits(J, cids)
        rr_t1, rr_t3 = top_hits(Q @ J, cids)                    # rand_rot, consistently
        # row_shuffle deranges the concept->vector map; build with J, then permute the rows.
        lg_shuffled = read((WU[cids] @ J)[perm] @ J.T)
        top3s = lg_shuffled.topk(3, dim=-1).indices
        rs_t1 = float((top3s[:, 0] == cids).float().mean())
        rs_t3 = float((top3s == cids.unsqueeze(1)).any(1).float().mean())

        # ---- R2 external agreement + R3 kurtosis ------------------------
        agree, kls, k_j, k_l, k_rot, k_shuf = [], [], [], [], [], []
        # NULL 2 for kurtosis: a norm-matched RANDOM J. Note that row-shuffling W_U is NOT a
        # valid kurtosis null -- permuting the logits leaves the distribution, and therefore
        # its kurtosis, exactly unchanged. (Row-shuffle remains a valid null for R1, where
        # the concept->vector correspondence is what is being destroyed.)
        gR = torch.Generator().manual_seed(7 + l)
        J_rand = torch.randn(d, d, generator=gR)
        J_rand = J_rand * (J.norm() / J_rand.norm())
        for p in EVAL_PROMPTS:
            ids = model.encode(p, max_length=128)
            with torch.no_grad(), ActivationRecorder(model.layers,
                                                     at=[l, model.n_layers - 1]) as rec:
                model.forward(ids)
                h_l = rec.activations[l][0, -1].detach().float()
                h_f = rec.activations[model.n_layers - 1][0, -1].detach().float()
                lg_j = model.unembed(h_l @ J.T).float()         # J-lens
                lg_l = model.unembed(h_l).float()               # logit lens
                lg_f = model.unembed(h_f).float()               # model's own final
                lg_rot = model.unembed(h_l @ (Q @ J).T).float() # null 1: random rotation of J
                lg_shuf = model.unembed(h_l @ J_rand.T).float() # null 2: norm-matched random J
            agree.append(float(lg_j.argmax() == lg_f.argmax()))
            # NOTE kl_div(input, target, log_target=True) computes KL(target || input).
            # Passing input=lens, target=final therefore yields KL(final || lens). We want
            # KL(lens || final), so the arguments are swapped. (Previously mislabelled.)
            kls.append(float(torch.nn.functional.kl_div(
                torch.log_softmax(lg_f, -1), torch.log_softmax(lg_j, -1),
                log_target=True, reduction="sum")))
            k_j.append(excess_kurtosis(lg_j)); k_l.append(excess_kurtosis(lg_l))
            k_rot.append(excess_kurtosis(lg_rot)); k_shuf.append(excess_kurtosis(lg_shuf))

        mean = lambda v: float(sum(v) / len(v))
        nulls = [x for x in (mean(k_l), mean(k_rot), mean(k_shuf)) if x == x]  # drop NaN
        if not nulls:
            raise SystemExit(f"all kurtosis nulls are NaN at layer {l}")
        null_max = max(nulls)
        sv = torch.linalg.svdvals(J)
        rows.append({
            "layer": l,
            "stable_rank": round(float(J.norm() ** 2 / sv[0] ** 2), 3),
            "d_model": int(d),
            # ActivationRecorder records block OUTPUTS, so l=0 is POST-block-0, not the
            # embedding. Depth is therefore (l+1)/n_layers, not l/(n_layers-1).
            "depth_pct": round(100 * (l + 1) / model.n_layers, 1),
            "R1_self_top1": round(r1_t1, 4), "R1_self_top3": round(r1_t3, 4),
            "R1_ctrl_randrot_top1": round(rr_t1, 4),
            "R1_ctrl_rowshuffle_top1": round(rs_t1, 4),
            "R1_controls_fire": bool(rr_t1 < 0.5 * r1_t1 and rs_t1 < 0.5 * r1_t1),
            "R2_top1_agreement": round(mean(agree), 4),
            "R2_kl_lens_vs_final": round(mean(kls), 4),
            "R3_kurt_jlens": round(mean(k_j), 3),
            "R3_kurt_logitlens": round(mean(k_l), 3),
            "R3_kurt_null_randrot": round(mean(k_rot), 3),
            "R3_kurt_null_randJ_normmatched": round(mean(k_shuf), 3),
            "R3_kurt_excess_over_max_null": round(mean(k_j) - null_max, 3),
        })
        print(f"  L{l:<3d} R1 {r1_t1:.3f}/{r1_t3:.3f} (ctrl {rr_t1:.3f}/{rs_t1:.3f})  "
              f"R2 agree={mean(agree):.2f} KL={mean(kls):.2f}  "
              f"R3 excess={mean(k_j) - null_max:+.2f}  srank={float(J.norm()**2/sv[0]**2):.1f}/{d}")

    best = max(rows, key=lambda r: r["R3_kurt_excess_over_max_null"])
    out = {
        "experiment": "T3 read audit (Claim 1a)",
        "status": "EXPLORATORY unless a committed PREREG_PYTHIA_READ.md is cited here",
        "prereg": None,
        "model": a.model, "lens": a.lens,
        "lens_n_prompts": lens.n_prompts, "d_model": lens.d_model,
        "n_layers": model.n_layers, "n_concepts": n_c,
        "vocab_size": int(WU.shape[0]),
        "centered": False,
        "env": {"transformers": transformers.__version__, "torch": torch.__version__,
                "device": "cpu", "dtype": "float32"},
        "jlens_commit": "581d398613e5602a5af361e1c34d3a92ea82ba8e",
        "band_peak_kurtosis_excess": {"layer": best["layer"], "depth_pct": best["depth_pct"],
                                      "excess": best["R3_kurt_excess_over_max_null"]},
        "any_layer_beats_all_nulls": bool(best["R3_kurt_excess_over_max_null"] > 0),
        "rows": rows,
        "runtime_s": round(time.perf_counter() - t0, 1),
    }
    json.dump(out, open(a.out, "w"), indent=1)
    print(f"\n  peak kurtosis excess: L{best['layer']} ({best['depth_pct']}% depth) "
          f"= {best['R3_kurt_excess_over_max_null']:+.3f}")
    print(f"  beats all nulls somewhere: {out['any_layer_beats_all_nulls']}")
    print(f"  wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
